sys.source(file.path(PROJECT_DIR, "scripts", "00_setup.R"), envir = globalenv())

# ── Load checkpoints ──────────────────────────────────────────
load(file.path(paths$rdata, "checkpoint_01.RData"))
load(file.path(paths$rdata, "checkpoint_03.RData"))
message("Checkpoints 01 and 03 loaded")

while (dev.cur() > 1) dev.off()   # clear any stale devices

# ── Local constants ───────────────────────────────────────────
FDR_CUTOFF <- 0.1   # must match the cutoff used in 03_analysis1_seven_group.R

# Colorblind-friendly palette for the 7 treatment groups.
# NOTE: keep this in sync with GROUP_COLOURS in 02_qc_plots.R if that
# script's exact hex values differ — shown here as Okabe-Ito equivalents
# so this figure's colors match the rest of the manuscript figure set.
GROUP_COLOURS <- c(
  "Sx"        = "#E69F00",
  "CTx"       = "#D55E00",
  "CTx + IO"  = "#56B4E9",
  "CTx + RTx" = "#0072B2",
  "IO"        = "#009E73",
  "Other"     = "#999999",
  "TKI"       = "#CC79A7"
)

# ── Local functions ───────────────────────────────────────────
safe_write_csv <- function(df, path) readr::write_csv(df, path, na = "")

sanitize_filename <- function(x) {
  out <- gsub("[^A-Za-z0-9]+", "_", as.character(x))
  out <- gsub("^_+|_+$", "", out)
  ifelse(nzchar(out), out, "unnamed")
}

akila_volcano_theme <- function() {
  theme_bw(base_size = 14) +
    theme(
      panel.border      = element_rect(colour = "black", fill = NA, linewidth = 0.8),
      panel.grid.minor  = element_blank(),
      plot.title        = element_text(face = "bold", size = 15),
      plot.subtitle     = element_text(size = 11, colour = "grey30"),
      axis.title        = element_text(face = "bold")
    )
}

# ── Build OVR FDR-hit summary table from analysis1_ovr_results ───
message("\n=== 03b | Building OVR FDR summary table ===")

if (!exists("analysis1_ovr_results") || length(analysis1_ovr_results) == 0) {
  stop("analysis1_ovr_results not found — confirm checkpoint_03.RData was generated by ",
       "an up-to-date run of 03_analysis1_seven_group.R")
}

ovr_summary <- purrr::imap_dfr(analysis1_ovr_results, function(df, grp) {
  tibble::tibble(
    group      = grp,
    n_tested   = nrow(df),
    n_fdr010   = sum(df$adj_p_value < FDR_CUTOFF, na.rm = TRUE)
  )
}) %>%
  dplyr::arrange(dplyr::desc(n_fdr010))

safe_write_csv(
  ovr_summary,
  file.path(paths$tables, "02_analysis1_seven_group", "analysis1_ovr_fdr_summary.csv")
)

message("OVR FDR summary:")
print(ovr_summary)

# ── Bar plot ───────────────────────────────────────────────────
message("\n=== 03b | Building OVR FDR summary bar plot ===")

plot_df <- ovr_summary %>%
  dplyr::mutate(group = factor(group, levels = group))  # preserve descending order

# Fall back to grey for any group not present in GROUP_COLOURS, rather than
# failing — keeps this script robust if group labels drift between runs.
fill_values <- GROUP_COLOURS[levels(plot_df$group)]
fill_values[is.na(fill_values)] <- "#7f7f7f"

p_ovr <- ggplot(plot_df, aes(x = group, y = n_fdr010, fill = group)) +
  geom_col(width = 0.65, colour = "black", linewidth = 0.3) +
  geom_text(aes(label = n_fdr010), vjust = -0.4, size = 4.2, fontface = "bold") +
  scale_fill_manual(values = fill_values, guide = "none") +
  labs(
    title    = "Analysis 1: One-vs-Rest Differential Expression by Treatment Group",
    subtitle = paste0("Proteins reaching FDR < ", FDR_CUTOFF, " per one-vs-rest contrast (of ",
                       max(plot_df$n_tested, na.rm = TRUE), " tested)"),
    x = NULL,
    y = "Proteins FDR < 0.1"
  ) +
  akila_volcano_theme() +
  theme(axis.text.x = element_text(angle = 30, hjust = 1))

stub_ovr <- file.path(paths$figures, "02_analysis1_seven_group", "analysis1_ovr_fdr_summary_barplot")

cairo_pdf(paste0(stub_ovr, ".pdf"), width = 7.5, height = 5.5)
print(p_ovr)
dev.off()

png(paste0(stub_ovr, ".png"), width = 7.5, height = 5.5, units = "in", res = 300, bg = "white")
print(p_ovr)
dev.off()

message("OVR FDR summary bar plot saved: ", stub_ovr, ".pdf / .png")
message("\n03b_analysis1_ovr_fdr_barplot.R complete")
