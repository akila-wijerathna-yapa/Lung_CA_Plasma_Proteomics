safe_write_csv <- function(df, path) readr::write_csv(df, path, na = "")

coerce_event_indicator <- function(x) {
  raw_chr <- trimws(as.character(x))
  op  <- options(warn = -1); out <- as.numeric(raw_chr); options(op)
  out
}

# Build one protein's KM step-curve data (long format, ready for facet_wrap)
build_efs_km_curve <- function(sample_df, expr_vec, protein_label, id) {
  df <- sample_df %>%
    dplyr::mutate(
      expr  = expr_vec[sample_id],
      time  = as.numeric(efs_months),
      event = coerce_event_indicator(efs_event)
    ) %>%
    dplyr::filter(!is.na(expr), !is.na(time), !is.na(event))

  if (nrow(df) < 10 || sum(df$event) < 4) return(NULL)

  med <- median(df$expr, na.rm = TRUE)
  df$group <- ifelse(df$expr >= med, "High", "Low")

  fit <- survival::survfit(survival::Surv(time, event) ~ group, data = df)
  sd  <- survival::survdiff(survival::Surv(time, event) ~ group, data = df)
  logrank_p <- pchisq(sd$chisq, df = 1, lower.tail = FALSE)

  curve <- broom::tidy(fit) %>%
    dplyr::mutate(
      group   = gsub("^group=", "", strata),
      protein = paste0(protein_label, "  (n=", nrow(df), ", p=", signif(logrank_p, 3), ")")
    )

  list(
    curve   = curve,
    summary = tibble::tibble(
      protein = protein_label, nELISA_ID = id, n = nrow(df),
      n_events = sum(df$event), n_low = sum(df$group == "Low"),
      n_high = sum(df$group == "High"), logrank_p = logrank_p
    )
  )
}

